SCRATCH = ".scratch"
BOARD = "PROGRESS.md"
WORKSTREAMS = "workstreams.md"
MARKER_PREFIX = "<!-- Generated by scripts/progress.py"
OPEN = ("ready-for-agent", "ready-for-human", "needs-triage", "needs-info")
TERMINAL = ("done", "resolved", "wontfix")
STATUSES = set(OPEN) | set(TERMINAL) | {"claimed"}
MAX_PLANS = 50
MAX_TICKETS = 500
MAX_WORKSTREAMS = 6
MAX_BYTES = 256 * 1024
TOTAL_BYTES = 4 * 1024 * 1024
HEAD_LINES = 40
BRIEF_LIMIT = 700
STALE_CLAIM_DAYS = 7
GIT_TIMEOUT = 5
GIT_BUDGET = 12
MAX_DONE_LOOKUPS = 20
COMMENT_CHARS = 120
ERROR_CODES = ("unknown-status", "unknown-blocker", "unparsed-blockers", "blocked-by-cycle", "unknown-workstream",
               "misclaim", "duplicate-number", "unreadable", "missing-title", "bad-phase", "bad-verify")

FIELD = re.compile(r"^\s*(?:\*\*)?(status|blocked by|phase|workstream|claimed by|verify)(?:\*\*)?\s*:\s*(?:\*\*)?\s*(.*?)\s*$",
                   re.IGNORECASE)
TITLE = re.compile(r"^#\s+(\d{2,3})\s*:\s*(.+?)\s*$")
FILENAME = re.compile(r"^(\d{2,3})-[A-Za-z0-9._-]+\.md$")
NUMBER = re.compile(r"(?<![\d.])(\d{2,3})(?![\d.])")
DATE = re.compile(r"\b(\d{4}-\d{2}-\d{2})\b")
REQUEST = re.compile(r"^\s*-?\s*Request\s+(\d{4}-\d{2}-\d{2})\s*:\s*(.*\S)\s*$", re.IGNORECASE)
GATE = re.compile(r"^phase\s+(\d+)\s+review\b", re.IGNORECASE)
PHASE_LINE = re.compile(r"^\s*(\d{1,2})\.\s+(.+?)\s*$")
SLUG = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$")
BRANCH = re.compile(r"^[A-Za-z0-9][A-Za-z0-9/._-]{0,127}$")
PATHGLOB = re.compile(r"^[A-Za-z0-9*?_./\[\]-]{1,200}$")
MARKER_HASH = re.compile(r"\(sources ([0-9a-f]{8})\)")
ACCEPTANCE = re.compile(r"^\s*- \[( |x|X)\]")
TABLE_ROW = re.compile(r"^\s*\|(.+)\|\s*$")
NO_BLOCKERS = {"", "none", "no blockers", "n/a", "na", "-", "none (can start immediately)"}
REQUEST_CLOSE = re.compile(r"^\s*-?\s*(?:Applied|Declined)\s+\d{4}-\d{2}-\d{2}\b", re.IGNORECASE)
NOTE_CLOSE = re.compile(r"^(\d{2,3})\s*:\s*(?:applied|declined)\b", re.IGNORECASE)
DONE_LINE = re.compile(r"^\s*-?\s*Done\s+\d{4}-\d{2}-\d{2}\s*:", re.IGNORECASE)
TRAILING_PUNCTUATION = re.compile(r"[\s.,;:!()\-\u2013\u2014]+$")


class ProgressError(ValueError):
    pass


@dataclasses.dataclass
class Ticket:
    number: int
    path: str
    title: str = ""
    status: Optional[str] = None
    blockers: List[int] = dataclasses.field(default_factory=list)
    blockers_unparsed: bool = False
    phase: int = 1
    workstream: Optional[str] = None
    claimed_by: Optional[str] = None
    claimed_on: Optional[datetime.date] = None
    verify: int = 1
    last_comment: str = ""
    done_line: str = ""
    requests: List[str] = dataclasses.field(default_factory=list)
    acceptance_done: int = 0
    acceptance_total: int = 0
    errors: List[str] = dataclasses.field(default_factory=list)
    blocked: bool = False
    gate: bool = False
    branch: Optional[str] = None
    integrated: bool = False
    awaiting_integration: bool = False
    done_sha: Optional[str] = None
    foreign_only: bool = False

    @property
    def terminal(self) -> bool:
        return self.status in TERMINAL

    @property
    def claimed(self) -> bool:
        return self.status == "claimed"


@dataclasses.dataclass
class Phase:
    number: int
    name: str
    goal: str = ""
    exit: str = ""


@dataclasses.dataclass
class Workstream:
    name: str
    branch: str
    owns: List[str]
    harness: str = ""
    where: str = "here"


@dataclasses.dataclass
class Plan:
    slug: str
    directory: Path
    kind: str = "plan"
    phases: Dict[int, Phase] = dataclasses.field(default_factory=dict)
    tickets: Dict[int, Ticket] = dataclasses.field(default_factory=dict)
    workstreams: Dict[str, Workstream] = dataclasses.field(default_factory=dict)
    base: str = ""
    integration: str = ""
    remote: str = ""
    shared: List[str] = dataclasses.field(default_factory=list)
    integrator_notes: List[str] = dataclasses.field(default_factory=list)
    closed_requests: Set[int] = dataclasses.field(default_factory=set)
    notices: List[str] = dataclasses.field(default_factory=list)
    errors: List[Tuple[int, str]] = dataclasses.field(default_factory=list)
    sources: List[Tuple[str, bytes]] = dataclasses.field(default_factory=list)
    current_phase: Optional[int] = None
    frontier: List[int] = dataclasses.field(default_factory=list)
    attention: List[str] = dataclasses.field(default_factory=list)
    completed: bool = False
    overlay: bool = False
    checkout_role: str = "none"
    resolved: Set[int] = dataclasses.field(default_factory=set)
    behind: Dict[str, Optional[bool]] = dataclasses.field(default_factory=dict)
    worktrees: Dict[str, str] = dataclasses.field(default_factory=dict)
    fetch_time: Optional[str] = None
    integration_order: List[Tuple[int, str, str]] = dataclasses.field(default_factory=list)
    orphaned: Dict[int, str] = dataclasses.field(default_factory=dict)
    claim_differs: List[int] = dataclasses.field(default_factory=list)

    @property
    def integration_branch(self) -> str:
        return self.integration or "integrate/" + self.slug

    @property
    def parallel(self) -> bool:
        return bool(self.workstreams)

    @property
    def active(self) -> bool:
        return self.kind == "plan" and bool(self.tickets) and not self.completed

    def phase_numbers(self) -> List[int]:
        numbers = set(self.phases) | {ticket.phase for ticket in self.tickets.values()}
        return sorted(numbers)


