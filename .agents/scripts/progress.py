def git_env() -> Dict[str, str]:
    return {**os.environ, "GIT_OPTIONAL_LOCKS": "0"}


def run_git(project: Path, args: List[str], deadline: float, stdin: Optional[bytes] = None) -> Tuple[Optional[int], bytes]:
    """One bounded git process; (None, b'') on any failure. Never raises, never fetches."""
    git = shutil.which("git")
    remaining = deadline - time.monotonic()
    if not git or remaining <= 0:
        return None, b""
    try:
        result = subprocess.run([git, "-C", str(project), "--no-optional-locks", "-c", "core.fsmonitor=false", *args],
                                input=stdin, stdin=None if stdin is not None else subprocess.DEVNULL,
                                stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
                                timeout=min(GIT_TIMEOUT, remaining), env=git_env())
    except (OSError, subprocess.SubprocessError, ValueError):
        return None, b""
    return result.returncode, result.stdout


def cat_file_batch(project: Path, objects: List[str], deadline: float) -> Dict[str, bytes]:
    """Contents of '<ref>:<path>' objects from one git process, paired with the requests in order."""
    found: Dict[str, bytes] = {}
    if not objects:
        return found
    code, data = run_git(project, ["cat-file", "--batch"], deadline, stdin=("\n".join(objects) + "\n").encode("utf-8"))
    if code != 0:
        return found
    position = 0
    for name in objects:
        newline = data.find(b"\n", position)
        if newline < 0:
            break
        header = data[position:newline].decode("utf-8", errors="replace").split()
        position = newline + 1
        if len(header) >= 2 and header[-1] in {"missing", "ambiguous"}:
            continue
        if len(header) < 3 or not header[2].isdigit():
            break
        size = int(header[2])
        if size <= MAX_BYTES:
            found[name] = data[position:position + size]
        position += size + 1
    return found


def common_git_dir(project: Path) -> Optional[Path]:
    dotgit = project / ".git"
    try:
        if dotgit.is_symlink():
            return None
        if dotgit.is_file():
            pointer = dotgit.read_text(encoding="utf-8", errors="replace").strip()
            if not pointer.startswith("gitdir:"):
                return None
            git_dir = Path(pointer[len("gitdir:"):].strip())
            if not git_dir.is_absolute():
                git_dir = (project / git_dir).resolve()
            common = git_dir / "commondir"
            if common.is_file():
                return (git_dir / common.read_text(encoding="utf-8", errors="replace").strip()).resolve()
            return git_dir
        if dotgit.is_dir():
            return dotgit
    except (OSError, RuntimeError):
        return None
    return None


def fetch_time(project: Path) -> Optional[str]:
    common = common_git_dir(project)
    if common is None:
        return None
    try:
        stamp = (common / "FETCH_HEAD").stat().st_mtime
    except OSError:
        return None
    return datetime.datetime.fromtimestamp(stamp, datetime.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")


COPIED_FIELDS = ("status", "claimed_by", "claimed_on", "last_comment", "requests", "acceptance_done", "acceptance_total", "verify")


def overlay(plan: Plan, project: Path, branch: Optional[str]) -> None:
    """Read each ticket's state from its owner's branch and the integration branch; never fetch."""
    if not plan.parallel:
        return
    deadline = time.monotonic() + GIT_BUDGET
    if not (project / ".git").exists() or not shutil.which("git"):
        plan.notices.append("parallel view unavailable: this folder is not a git checkout or git is not on PATH")
        return
    _, stream, role = workstream_for_branch([plan], branch)
    plan.checkout_role = role
    code, out = run_git(project, ["for-each-ref", "--format=%(refname) %(objectname)", "refs/heads/", "refs/remotes/origin/"], deadline)
    if code != 0:
        plan.notices.append("parallel view unavailable: git refs could not be read")
        return
    refs: Dict[str, str] = {}
    for line in out.decode("utf-8", errors="replace").splitlines():
        name, _, oid = line.partition(" ")
        if name and oid:
            refs[name] = oid

    def ref_for(name: str, local_first: bool = False) -> Optional[str]:
        local, remote = "refs/heads/" + name, "refs/remotes/origin/" + name
        order = (local, remote) if local_first or plan.remote != "origin" else (remote, local)
        for ref in order:
            if ref in refs:
                return ref
        return None

    own_branch = stream.branch if (role == "workstream" and stream is not None) else (plan.integration_branch if role == "integration" else None)
    owner_refs: Dict[str, str] = {}
    for name, ws in plan.workstreams.items():
        if ws.branch == own_branch:
            continue
        ref = ref_for(ws.branch, local_first=ws.where == "here")
        if ref:
            owner_refs[name] = ref
    integration_ref = None if role == "integration" else ref_for(plan.integration_branch, local_first=True)
    origin_own = None
    if own_branch and plan.remote == "origin" and "refs/remotes/origin/" + own_branch in refs:
        origin_own = "refs/remotes/origin/" + own_branch
    needed = sorted(set(owner_refs.values()) | ({integration_ref} if integration_ref else set()) | ({origin_own} if origin_own else set()))
    hashed_refs: set = set()

    def hash_ref(ref: Optional[str]) -> None:
        if ref and ref in refs and ref not in hashed_refs:
            hashed_refs.add(ref)
            plan.sources.append(("ref:" + ref, refs[ref].encode("utf-8")))

    for ref in needed:
        hash_ref(ref)
    issues_dir = ".scratch/{}/issues/".format(plan.slug)
    listing: Dict[str, List[str]] = {}
    for ref in needed:
        code, out = run_git(project, ["ls-tree", "-r", "--name-only", ref, "--", issues_dir], deadline)
        names = out.decode("utf-8", errors="replace").splitlines() if code == 0 else []
        listing[ref] = [path for path in names if FILENAME.match(path.rsplit("/", 1)[-1])][:MAX_TICKETS]
    objects = ["{}:{}".format(ref, path) for ref, paths in listing.items() for path in paths]
    blobs = cat_file_batch(project, objects, deadline)
    views: Dict[str, Dict[int, Ticket]] = {ref: {} for ref in listing}
    for key, data in blobs.items():
        ref, path = key.split(":", 1)
        number = int(FILENAME.match(path.rsplit("/", 1)[-1]).group(1))
        if number in views[ref]:
            views[ref][number].errors.append("duplicate-number")
            continue
        views[ref][number] = parse_ticket(number, path, decode(data))
    integration_view = plan.tickets if role == "integration" else (views.get(integration_ref, {}) if integration_ref else {})
    local = plan.tickets
    for ref in needed:
        for number, view in views[ref].items():
            if number not in local:
                view.foreign_only = True
                local[number] = view
            elif ("duplicate-number" in view.errors or view.path != local[number].path) and "duplicate-number" not in local[number].errors:
                local[number].errors.append("duplicate-number")
    own_name = stream.name if (role == "workstream" and stream is not None) else None
    # Snapshot the integration branch's statuses first: on the integration checkout the view shares objects with the local tree.
    integration_status = {number: (view.status, view.workstream) for number, view in integration_view.items()}
    for number, ticket in local.items():
        owner = ticket.workstream or "integrator"
        if number in integration_status and integration_status[number][1]:
            owner = integration_status[number][1]
            ticket.workstream = owner
        if owner in owner_refs:
            view = views[owner_refs[owner]].get(number)
            if view is not None:
                for field in COPIED_FIELDS:
                    setattr(ticket, field, getattr(view, field))
                ticket.branch = plan.workstreams[owner].branch
        elif owner == "integrator" and integration_ref and number in integration_view:
            view = integration_view[number]
            for field in COPIED_FIELDS:
                setattr(ticket, field, getattr(view, field))
            ticket.branch = plan.integration_branch
        elif owner == own_name and own_branch:
            ticket.branch = own_branch
        ticket.integrated = number in integration_status and integration_status[number][0] in {"done", "resolved"}
        ticket.awaiting_integration = ticket.status == "done" and not ticket.integrated and owner != "integrator"
        for name, ref in owner_refs.items():
            if name == owner:
                continue
            other = views[ref].get(number)
            if other is not None and other.claimed:
                plan.orphaned[number] = plan.workstreams[name].branch
        if origin_own and owner == own_name:
            remote_view = views[origin_own].get(number)
            if remote_view is not None and ticket.claimed and remote_view.claimed and (remote_view.claimed_by or "") != (ticket.claimed_by or ""):
                plan.claim_differs.append(number)
    plan.resolved = {number for number, (status, _) in integration_status.items() if status in {"done", "resolved"}}
    for number, ticket in local.items():
        if ticket.branch in (None, own_branch) and ticket.status in {"done", "resolved"}:
            plan.resolved.add(number)
    plan.overlay = True
    lookups = 0
    for number, ticket in sorted(local.items()):
        if not ticket.awaiting_integration or lookups >= MAX_DONE_LOOKUPS:
            continue
        owner = ticket.workstream or ""
        ref = owner_refs.get(owner) or ("refs/heads/" + own_branch if owner == own_name and own_branch else None)
        if ref is None:
            continue
        lookups += 1
        code, out = run_git(project, ["log", "-1", "--format=%H", ref, "--", ticket.path], deadline)
        sha = out.decode("utf-8", errors="replace").strip()
        if code == 0 and re.fullmatch(r"[0-9a-f]{40,64}", sha):
            ticket.done_sha = sha
            plan.integration_order.append((number, plan.workstreams[owner].branch, sha))
    integration_for_ancestry = integration_ref or ("refs/heads/" + plan.integration_branch if "refs/heads/" + plan.integration_branch in refs else None)
    for name, ws in plan.workstreams.items():
        ws_ref = owner_refs.get(name) or ("refs/heads/" + own_branch if ws.branch == own_branch and own_branch and "refs/heads/" + own_branch in refs else None)
        hash_ref(integration_for_ancestry)
        hash_ref(ws_ref)
        if integration_for_ancestry is None or ws_ref is None:
            plan.behind[name] = None
            continue
        code, _ = run_git(project, ["merge-base", "--is-ancestor", integration_for_ancestry, ws_ref], deadline)
        plan.behind[name] = None if code is None or code > 1 else code == 1
    code, out = run_git(project, ["worktree", "list", "--porcelain"], deadline)
    if code == 0:
        plan.sources.append(("worktrees", out))
        current = None
        for line in out.decode("utf-8", errors="replace").splitlines():
            if line.startswith("worktree "):
                current = line[len("worktree "):]
            elif line.startswith("branch refs/heads/") and current:
                plan.worktrees[line[len("branch refs/heads/"):]] = current
    if plan.remote == "origin":
        plan.fetch_time = fetch_time(project)
        plan.sources.append(("fetch", (plan.fetch_time or "").encode("utf-8")))
    if time.monotonic() > deadline:
        plan.notices.append("parallel view incomplete: the git budget of {} seconds ran out".format(GIT_BUDGET))


