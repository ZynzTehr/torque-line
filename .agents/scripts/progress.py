def checkout_branch(project: Path) -> Optional[str]:
    """The checked-out branch, read from .git without running git; None when detached or absent."""
    dotgit = project / ".git"
    try:
        if dotgit.is_symlink():
            return None
        if dotgit.is_file():
            pointer = dotgit.read_text(encoding="utf-8", errors="replace").strip()
            if not pointer.startswith("gitdir:"):
                return None
            git_dir = Path(pointer[len("gitdir:"):].strip())
            if not git_dir.is_absolute():
                git_dir = (project / git_dir).resolve()
        elif dotgit.is_dir():
            git_dir = dotgit
        else:
            return None
        head = (git_dir / "HEAD").read_text(encoding="utf-8", errors="replace").strip()
    except (OSError, RuntimeError):
        return None
    if head.startswith("ref: refs/heads/"):
        branch = head[len("ref: refs/heads/"):]
        return branch if BRANCH.match(branch) and ".." not in branch else None
    return None


def git_query(project: Path, args: List[str]) -> Optional[int]:
    """Exit code of one bounded, read-only git query; None when git is absent or failed to run."""
    git = shutil.which("git")
    if not git:
        return None
    try:
        result = subprocess.run([git, "-C", str(project), "--no-optional-locks", *args],
                                stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                                timeout=GIT_TIMEOUT, env=git_env())
    except (OSError, subprocess.SubprocessError):
        return None
    return result.returncode


def is_ignored(project: Path) -> Optional[bool]:
    """Whether /PROGRESS.md is ignored by git: None when the project is not a git checkout."""
    if not (project / ".git").exists():
        return None
    code = git_query(project, ["check-ignore", "-q", BOARD])
    if code in (0, 1):
        return code == 0
    try:
        text = (project / ".gitignore").read_text(encoding="utf-8", errors="replace")
    except OSError:
        return False
    return any(line.strip() in {"/" + BOARD, BOARD, "/" + BOARD.lower(), BOARD.lower()} for line in text.splitlines())


def is_tracked(project: Path) -> bool:
    """Whether a PROGRESS.md was committed by mistake, which no ignore rule can hide."""
    return git_query(project, ["ls-files", "--error-unmatch", BOARD]) == 0


def board_kind(path: Path) -> Tuple[str, str]:
    """('generated', hash), ('hand-written', '') or ('unreadable', '') for an existing board file."""
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as handle:
            first = handle.readline()
    except OSError:
        return "unreadable", ""
    if not first.startswith(MARKER_PREFIX):
        return "hand-written", ""
    match = MARKER_HASH.search(first)
    return "generated", (match.group(1) if match else "")


def write_board(project: Path, plans: List[Plan], now: Optional[datetime.datetime] = None, notices: Optional[List[str]] = None) -> str:
    """Write the generated board; returns written, unchanged, removed, absent, hand-written, not-ignored, tracked or refused."""
    path = project / BOARD
    try:
        if path.is_symlink():
            return "refused"
        exists = path.exists()
    except OSError:
        return "refused"
    kind, current_hash = board_kind(path) if exists else ("absent", "")
    if kind == "hand-written":
        return "hand-written"
    if kind == "unreadable":
        return "refused"
    if not any(plan.kind == "plan" for plan in plans):
        # A wayfinder-only project has no plan of record; a stale generated board goes away.
        if exists:
            try:
                path.unlink()
            except OSError:
                return "refused"
            return "removed"
        return "absent"
    ignored = is_ignored(project)
    if ignored is False:
        return "tracked" if is_tracked(project) else "not-ignored"
    text, digest = render(plans, now, notices)
    if exists and current_hash == digest:
        return "unchanged"
    try:
        fd, temporary = tempfile.mkstemp(prefix=".progress-", dir=project)
    except OSError:
        return "refused"
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(text)
            handle.flush()
            os.fsync(handle.fileno())
        os.chmod(temporary, 0o644)
        os.replace(temporary, path)
    except OSError:
        return "refused"
    finally:
        if os.path.exists(temporary):
            try:
                os.unlink(temporary)
            except OSError:
                pass
    return "written"


