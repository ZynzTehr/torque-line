# Rendering


def num(number: int) -> str:
    return "{:02d}".format(number)


def phase_state(plan: Plan, number: int) -> str:
    members = [t for t in plan.tickets.values() if t.phase == number]
    if members and all(t.terminal for t in members):
        return "complete"
    if plan.current_phase is not None and number < plan.current_phase:
        return "complete"
    if number == plan.current_phase:
        open_members = [t for t in members if not t.terminal]
        if open_members and all(t.status == "ready-for-human" for t in open_members):
            return "awaiting review"
        return "current"
    return "pending"


def render_plan(plan: Plan) -> List[str]:
    lines: List[str] = []
    tickets = plan.tickets
    numbers = plan.phase_numbers()
    total = len(tickets)
    done = sum(1 for t in tickets.values() if t.terminal)
    claimed = [n for n, t in sorted(tickets.items()) if t.claimed]
    blocked = [n for n, t in sorted(tickets.items()) if not t.terminal and not t.claimed and t.blocked]
    if plan.completed:
        lines.append("## {}: complete ({} of {} tickets)".format(plan.slug, done, total))
        lines.append("")
        return lines
    k = plan.current_phase
    name = cell(plan.phases[k].name) if k in plan.phases else "phase {}".format(k)
    lines.append("## {}: phase {} of {}, {}".format(plan.slug, numbers.index(k) + 1 if k in numbers else k, len(numbers), name))
    lines.append("")
    lines.append("Tickets: {} done, {} in progress, {} ready, {} blocked, {} total.".format(
        done, len(claimed), len(plan.frontier), len(blocked), total))
    lines.append("")
    if plan.parallel and plan.remote == "origin":
        lines.append("Remote view as of {}.".format(plan.fetch_time or "an unknown time (no fetch recorded)"))
        lines.append("")
    lines.append("| Phase | Name | Done | Total | State |")
    lines.append("|---|---|---|---|---|")
    for number in numbers:
        members = [t for t in tickets.values() if t.phase == number]
        title = cell(plan.phases[number].name) if number in plan.phases else ""
        lines.append("| {} | {} | {} | {} | {} |".format(number, title, sum(1 for t in members if t.terminal), len(members), phase_state(plan, number)))
    lines.append("")
    if claimed:
        lines.append("### In progress")
        lines.append("")
        branch_col = " Branch |" if plan.parallel else ""
        lines.append("| Ticket | Who | Since |" + branch_col + " Last note |")
        lines.append("|---|---|---|" + ("---|" if plan.parallel else "") + "---|")
        for n in claimed:
            t = tickets[n]
            branch_cell = " {} |".format(t.branch or (plan.workstreams[t.workstream].branch if t.workstream in plan.workstreams else "")) if plan.parallel else ""
            lines.append("| {} {} | {} | {} |{} {} |".format(num(n), cell(t.title), cell(t.claimed_by or "unknown"),
                                                        t.claimed_on.isoformat() if t.claimed_on else "", branch_cell, cell(t.last_comment)))
        lines.append("")
    lines.append("### Ready to claim")
    lines.append("")
    if plan.frontier:
        for number in numbers:
            ready = [n for n in plan.frontier if tickets[n].phase == number]
            if ready:
                lines.append("- Phase {}: {}".format(number, ", ".join("{} {}".format(num(n), cell(tickets[n].title)) for n in ready)))
    else:
        unblock = next_unblock(plan)
        lines.append("None." + (" Next unblocks: {}.".format(unblock) if unblock else ""))
    lines.append("")
    if blocked:
        lines.append("### Blocked")
        lines.append("")
        lines.append("| Ticket | Waits on |")
        lines.append("|---|---|")
        for n in blocked:
            t = tickets[n]
            waits = ", ".join(num(b) + blocker_note(plan, b) for b in t.blockers if not released(plan, b))
            if t.blockers_unparsed:
                waits = (waits + ", " if waits else "") + "an unparsed Blocked by line"
