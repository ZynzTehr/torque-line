# Reading


def checked_project(project) -> Path:
    supplied = Path(project)
    if not supplied.is_absolute():
        supplied = Path.cwd() / supplied
    try:
        if supplied.is_symlink():
            raise ProgressError("A symlink project path is not supported.")
        project = Path(os.path.realpath(supplied))
        if not project.is_dir():
            raise ProgressError("Project directory does not exist.")
    except (OSError, RuntimeError):
        raise ProgressError("Project directory is unreadable.") from None
    return project


class Budget:
    def __init__(self, total: int = TOTAL_BYTES):
        self.remaining = total
        self.exhausted = False


def read_bounded(path: Path, budget: Budget) -> Optional[bytes]:
    """Read one tracker file without following symlinks; None when unusable."""
    if budget.exhausted:
        return None
    try:
        fd = os.open(path, os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0))
    except OSError:
        return None
    try:
        with os.fdopen(fd, "rb") as handle:
            info = os.fstat(handle.fileno())
            if not stat.S_ISREG(info.st_mode) or info.st_size > MAX_BYTES:
                return None
            if info.st_size > budget.remaining:
                budget.exhausted = True
                return None
            data = handle.read(MAX_BYTES + 1)
    except OSError:
        return None
    if len(data) > MAX_BYTES:
        return None
    budget.remaining -= len(data)
    return data


def decode(data: bytes) -> str:
    return data.decode("utf-8", errors="replace").replace("\r\n", "\n")


def parse_ticket(number: int, relative: str, text: str) -> Ticket:
    ticket = Ticket(number=number, path=relative)
    lines = text.split("\n")
    for line in lines[:HEAD_LINES]:
        match = TITLE.match(line)
        if match and not ticket.title:
            ticket.title = match.group(2)
            continue
        match = FIELD.match(line)
        if not match:
            continue
        name, value = match.group(1).lower(), match.group(2).strip().rstrip("*").strip()
        if name == "status":
            if value:
                ticket.status = value.lower()
        elif name == "blocked by":
            numbers = [int(token) for token in NUMBER.findall(DATE.sub(" ", value))]
            ticket.blockers = sorted(set(numbers))
            bare = TRAILING_PUNCTUATION.sub("", value.strip()).lower()
            if value and not numbers and bare not in NO_BLOCKERS and not bare.startswith("none"):
                ticket.blockers_unparsed = True
        elif name == "phase":
            if re.fullmatch(r"\d{1,2}", value) and int(value) >= 1:
                ticket.phase = int(value)
            elif value:
                ticket.errors.append("bad-phase")
        elif name == "workstream":
            if value:
                ticket.workstream = value
        elif name == "claimed by":
            if value:
                found = DATE.search(value)
                who = value
                if found:
                    who = value[:found.start()] + value[found.end():]
                    try:
                        ticket.claimed_on = datetime.date.fromisoformat(found.group(1))
                    except ValueError:
                        ticket.claimed_on = None
                who = re.sub(r"[\s,;]+$", "", who.strip()).strip()
                ticket.claimed_by = (who or "unknown")[:80]
        elif name == "verify":
            if value in {"1", "2", "3"}:
                ticket.verify = int(value)
            elif value:
                ticket.errors.append("bad-verify")
    if not ticket.title:
        ticket.errors.append("missing-title")
    if ticket.status is not None and ticket.status not in STATUSES:
        ticket.errors.append("unknown-status")
    in_comments = False
    for line in lines:
        if line.startswith("## "):
            in_comments = line.strip().lower() == "## comments"
            continue
        match = ACCEPTANCE.match(line)
        if match:
            ticket.acceptance_total += 1
            if match.group(1) in "xX":
                ticket.acceptance_done += 1
        if in_comments and line.strip() and not match:
            ticket.last_comment = line.strip().lstrip("- ").strip()[:COMMENT_CHARS]
            if DONE_LINE.match(line):
                ticket.done_line = ticket.last_comment
            request = REQUEST.match(line)
            if request:
                ticket.requests.append(request.group(2)[:COMMENT_CHARS])
            elif REQUEST_CLOSE.match(line):
                ticket.requests = []
    if GATE.match(ticket.title):
        ticket.gate = True
    return ticket


def parse_spec(text: str) -> Dict[int, Phase]:
    phases: Dict[int, Phase] = {}
    in_phases = False
    for line in text.split("\n"):
        if line.startswith("#"):
            in_phases = line.strip("# ").strip().lower() == "phases"
            continue
        if not in_phases:
            continue
        match = PHASE_LINE.match(line)
        if not match:
            continue
        number, rest = int(match.group(1)), match.group(2)
        name, _, remainder = rest.partition(". ")
        if not remainder:
            name, remainder = rest.rstrip("."), ""
        goal, _, exit_text = remainder.partition("Exit:")
        phases[number] = Phase(number=number, name=name.strip().rstrip("."), goal=goal.strip().rstrip("."),
                               exit=exit_text.strip().rstrip("."))
    return phases


def parse_workstreams(text: str, plan: Plan) -> None:
    rows: List[List[str]] = []
    in_notes = False
    for line in text.split("\n"):
        stripped = line.strip()
        if stripped.startswith("#"):
            in_notes = stripped.lstrip("# ").strip().lower() == "integrator notes"
            continue
        if in_notes:
            if stripped.startswith("- "):
                note = stripped[2:].strip()
                plan.integrator_notes.append(note[:COMMENT_CHARS])
                closed = NOTE_CLOSE.match(note)
                if closed:
                    plan.closed_requests.add(int(closed.group(1)))
            continue
        for key in ("base", "integration", "remote", "shared"):
            if stripped.lower().startswith(key + ":"):
                value = stripped.split(":", 1)[1].strip()
                if key == "shared":
                    plan.shared = [part.strip().strip("`") for part in value.split(",") if part.strip()]
                elif key in {"base", "integration"}:
                    if BRANCH.match(value) and ".." not in value:
                        setattr(plan, key, value)
                else:
                    plan.remote = value.lower() if value.lower() in {"origin", "none"} else ""
                break
        else:
            match = TABLE_ROW.match(line)
            if match:
                cells = [cell.strip().strip("`") for cell in match.group(1).split("|")]
                if cells and not set(cells[0]) <= set("-: "):
                    rows.append(cells)
    for cells in rows:
        if len(cells) < 3 or cells[0].lower() == "workstream":
            continue
        name, branch = cells[0], cells[1]
        if not SLUG.match(name) or not BRANCH.match(branch) or ".." in branch:
            plan.notices.append("workstreams.md row skipped: invalid name or branch")
            continue
        owns = [part.strip().strip("`") for part in cells[2].split(",") if part.strip()]
        owns = [glob for glob in owns if PATHGLOB.match(glob) and ".." not in glob]
        harness = cells[3].lower() if len(cells) > 3 else ""
        where = cells[4].strip() if len(cells) > 4 else ""
        where = where if SLUG.match(where) else ("here" if not where else "elsewhere")
        if len(plan.workstreams) >= MAX_WORKSTREAMS:
            plan.notices.append("workstreams.md lists more than {} workstreams; extra rows ignored".format(MAX_WORKSTREAMS))
            break
        plan.workstreams[name] = Workstream(name=name, branch=branch, owns=owns, harness=harness, where=where)


def plain_dir(path: Path) -> bool:
    try:
        return path.is_dir() and not path.is_symlink()
    except OSError:
        return False


def plain_file(path: Path) -> bool:
    try:
        return path.is_file() and not path.is_symlink()
    except OSError:
        return False


def discover(project: Path, budget: Optional[Budget] = None) -> Tuple[List[Plan], List[str]]:
    """Parse every plan under .scratch/; the caller computes derived state."""
    budget = budget or Budget()
    notices: List[str] = []
    scratch = project / SCRATCH
    if not plain_dir(scratch):
        return [], notices
    plans: List[Plan] = []
    try:
        entries = sorted(entry for entry in scratch.iterdir() if plain_dir(entry))
    except OSError:
        return [], ["the .scratch directory is unreadable"]
    for directory in entries:
        if not SLUG.match(directory.name):
            continue
        issues = directory / "issues"
        if not plain_dir(issues):
            continue
        try:
            listing = sorted(issues.iterdir())
        except OSError:
            continue
        files = [entry for entry in listing if FILENAME.match(entry.name) and not entry.is_symlink()]
        misnamed = sorted(entry.name for entry in listing if entry.name.lower().endswith(".md") and not FILENAME.match(entry.name))
        if not files:
            continue
        if len(plans) >= MAX_PLANS:
            notices.append("more than {} plans under .scratch/; the rest are not shown".format(MAX_PLANS))
            break
        plan = Plan(slug=directory.name, directory=directory, kind="wayfinder" if plain_file(directory / "map.md") else "plan")
        spec = directory / "spec.md"
        if plain_file(spec):
            data = read_bounded(spec, budget)
            if data is not None:
                plan.phases = parse_spec(decode(data))
                plan.sources.append((spec.relative_to(project).as_posix(), data))
        streams = directory / WORKSTREAMS
        if plain_file(streams):
            data = read_bounded(streams, budget)
            if data is not None:
                parse_workstreams(decode(data), plan)
                plan.sources.append((streams.relative_to(project).as_posix(), data))
        for path in files[:MAX_TICKETS]:
            number = int(FILENAME.match(path.name).group(1))
            relative = path.relative_to(project).as_posix()
            data = read_bounded(path, budget)
            if data is None:
                ticket = Ticket(number=number, path=relative, errors=["unreadable"])
            else:
                ticket = parse_ticket(number, relative, decode(data))
                plan.sources.append((relative, data))
            if number in plan.tickets:
                ticket.errors.append("duplicate-number")
                plan.tickets[number].errors.append("duplicate-number")
                plan.errors.append((number, "duplicate-number"))
                continue
            plan.tickets[number] = ticket
        if misnamed:
            plan.notices.append("ignored under issues/ because the name is not NN-<stem>.md: " + ", ".join(cell(name) for name in misnamed[:5])
                                + (" and {} more".format(len(misnamed) - 5) if len(misnamed) > 5 else ""))
        if len(files) > MAX_TICKETS:
            plan.notices.append("plan truncated to {} tickets".format(MAX_TICKETS))
        if budget.exhausted:
            plan.notices.append("plan truncated: the read budget of {} MiB was reached".format(TOTAL_BYTES // (1024 * 1024)))
        plans.append(plan)
    return plans, notices


# ---------------------------------------------------------------------------
# Derivation


def resolves(ticket: Ticket) -> bool:
    """A blocker releases its dependents only when it was done or resolved; wontfix keeps them blocked."""
    return ticket.status in {"done", "resolved"}


def released(plan: Plan, number: int) -> bool:
    """In parallel mode a blocker counts only when done on the integration branch or in this checkout."""
    if plan.overlay:
        return number in plan.resolved
    return number in plan.tickets and resolves(plan.tickets[number])


def find_cycles(tickets: Dict[int, Ticket]) -> set:
    """Numbers that can reach themselves through Blocked by edges."""
    on_cycle: set = set()
    for start in tickets:
        seen: set = set()
        stack = list(tickets[start].blockers)
        while stack:
            number = stack.pop()
            if number == start:
                on_cycle.add(start)
                break
            if number in seen or number not in tickets:
                continue
            seen.add(number)
            stack.extend(tickets[number].blockers)
    return on_cycle


def compute(plan: Plan, now: datetime.datetime) -> Plan:
    tickets = plan.tickets
    cycles = find_cycles(tickets)
    for number, ticket in sorted(tickets.items()):
        for blocker in ticket.blockers:
            if blocker not in tickets:
                ticket.errors.append("unknown-blocker")
                break
        if ticket.blockers_unparsed:
            ticket.errors.append("unparsed-blockers")
        if number in cycles:
            ticket.errors.append("blocked-by-cycle")
        if plan.parallel:
            if ticket.workstream and ticket.workstream != "integrator" and ticket.workstream not in plan.workstreams:
                ticket.errors.append("unknown-workstream")
            if ticket.claimed and ticket.claimed_by and ticket.workstream:
                claimant = ticket.claimed_by.split("(")[0].strip()
                if claimant and claimant != ticket.workstream and claimant in plan.workstreams:
                    ticket.errors.append("misclaim")
        ticket.errors = list(dict.fromkeys(ticket.errors))
        for code in ticket.errors:
            if (number, code) not in plan.errors:
                plan.errors.append((number, code))
    for number, ticket in tickets.items():
        unresolved = [b for b in ticket.blockers if not released(plan, b)]
        ticket.blocked = bool(unresolved) or ticket.blockers_unparsed or number in cycles
    open_numbers = [n for n, t in tickets.items() if not t.terminal]
    plan.completed = not open_numbers and not any(t.awaiting_integration for t in tickets.values()) and not plan.orphaned
    plan.current_phase = min(tickets[n].phase for n in open_numbers) if open_numbers else None
    plan.frontier = sorted(n for n, t in tickets.items()
                           if not t.terminal and not t.claimed and not t.blocked and t.status in {"ready-for-agent", None})
    attention: List[str] = []
    for number, ticket in sorted(tickets.items()):
        if ticket.terminal:
            continue
        if ticket.status == "ready-for-human" and not ticket.blocked:
            attention.append("ticket {:02d} awaits a human (ready-for-human)".format(number))
        if ticket.status in {"needs-triage", "needs-info"}:
            attention.append("ticket {:02d} is {}".format(number, ticket.status))
        if ticket.claimed and ticket.claimed_on and (now.date() - ticket.claimed_on).days > STALE_CLAIM_DAYS:
            attention.append("ticket {:02d} has been claimed since {} ({} days)".format(
                number, ticket.claimed_on.isoformat(), (now.date() - ticket.claimed_on).days))
        wontfix = [b for b in ticket.blockers if b in tickets and tickets[b].status == "wontfix"]
        if wontfix:
            attention.append("ticket {:02d} waits on wontfix ticket {}".format(number, ", ".join("{:02d}".format(b) for b in wontfix)))
        if ticket.requests and number not in plan.closed_requests:
            attention.append("ticket {:02d} has {} open request(s) for the integrator".format(number, len(ticket.requests)))
    for number, ticket in sorted(tickets.items()):
        if ticket.status == "done" and ticket.verify >= 2:
            done_line = ticket.done_line.lower()
            if "review:" not in done_line or re.search(r"review:\s*none\b", done_line):
                attention.append("ticket {:02d} is done at tier {} without a recorded review".format(number, ticket.verify))
    if plan.overlay:
        for number, ticket in sorted(tickets.items()):
            if ticket.awaiting_integration:
                attention.append("ticket {:02d} is done on {}, awaiting integration".format(number, ticket.branch or "its branch"))
        for number, branch in sorted(plan.orphaned.items()):
            attention.append("ticket {:02d} has an orphaned claim on {}".format(number, branch))
        for number in sorted(plan.claim_differs):
            attention.append("claim of ticket {:02d} here differs from origin; a second session may hold it".format(number))
        for name, behind in sorted(plan.behind.items()):
            if behind:
                attention.append("{} is behind {}; merge it forward before the next claim".format(name, plan.integration_branch))
    if plan.parallel and plan.integrator_notes:
        attention.append("{} integrator note(s) in workstreams.md".format(len(plan.integrator_notes)))
    plan.attention = attention
    return plan


def load(project: Path, now: Optional[datetime.datetime] = None) -> Tuple[List[Plan], List[str]]:
    now = now or utcnow()
    plans, notices = discover(project)
    branch = checkout_branch(project)
    for plan in plans:
        if plan.parallel:
            overlay(plan, project, branch)
        compute(plan, now)
    return plans, notices


def utcnow() -> datetime.datetime:
    return datetime.datetime.now(datetime.timezone.utc).replace(microsecond=0)


def sources_hash(plans: List[Plan]) -> str:
    digest = hashlib.sha256()
    for plan in plans:
        for relative, data in sorted(plan.sources):
            digest.update(relative.encode("utf-8") + b"\0")
            digest.update(hashlib.sha256(data).digest())
    return digest.hexdigest()[:8]


