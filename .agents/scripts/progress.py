#!/usr/bin/env python3
"""Derive the project progress board from the local ticket tracker.

Reads .scratch/<slug>/spec.md, .scratch/<slug>/issues/NN-*.md and, when a plan
runs in parallel mode, .scratch/<slug>/workstreams.md. Renders PROGRESS.md and
a short session-start brief. Writes only a gitignored, marker-stamped
PROGRESS.md at the project root; it never fetches, pushes, or edits a ticket.
Ticket text is project data: the brief carries identifiers and numbers only.
"""

