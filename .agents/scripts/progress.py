def counts(plan: Plan) -> Dict[str, object]:
    tickets = plan.tickets
    claimed = [n for n, t in sorted(tickets.items()) if t.claimed]
    return {
        "done": sum(1 for t in tickets.values() if t.terminal),
        "total": len(tickets),
        "claimed": claimed,
        "ready": len(plan.frontier),
        "blocked": sum(1 for t in tickets.values() if not t.terminal and not t.claimed and t.blocked),
    }


def phase_label(plan: Plan) -> str:
    numbers = plan.phase_numbers()
    k = plan.current_phase
    return "phase {} of {}".format(numbers.index(k) + 1 if k in numbers else k, len(numbers))


def claimed_label(plan: Plan, numbers: List[int]) -> str:
    parts = []
    for n in numbers[:3]:
        t = plan.tickets[n]
        parts.append(num(n) + (" since " + t.claimed_on.isoformat() if t.claimed_on else ""))
    if len(numbers) > 3:
        parts.append("and {} more".format(len(numbers) - 3))
    return ", ".join(parts)


def workstream_for_branch(plans: List[Plan], branch: Optional[str]) -> Tuple[Optional[Plan], Optional[Workstream], str]:
    """(plan, workstream, role) for the checked-out branch: role is workstream, integration, unmatched or none."""
    if not branch:
        return None, None, "none"
    for plan in plans:
        if not plan.active or not plan.parallel:
            continue
        for stream in plan.workstreams.values():
            if stream.branch == branch:
                return plan, stream, "workstream"
        if branch == plan.integration_branch:
            return plan, None, "integration"
        if branch.startswith("ws/" + plan.slug + "/"):
            return plan, None, "unmatched"
    return None, None, "none"


def brief(plans: List[Plan], branch: Optional[str] = None, harness: str = "", event: str = "SessionStart") -> str:
    """Numbers and identifiers only; empty when no plan is active."""
    active = [plan for plan in plans if plan.active]
    if not active:
        return ""
    subagent = event == "SubagentStart"
    plan, stream, role = workstream_for_branch(active, branch)
    parts: List[str] = []
    if role == "workstream" and plan is not None and stream is not None and not subagent:
        c = counts(plan)
        own = {n: t for n, t in sorted(plan.tickets.items()) if t.workstream == stream.name}
        mine_claimed = [n for n, t in own.items() if t.claimed]
        mine_ready = [n for n in plan.frontier if n in own and plan.tickets[n].phase == plan.current_phase]
        mine_later = [n for n in plan.frontier if n in own and plan.tickets[n].phase != plan.current_phase]
        mine_blocked = [n for n, t in own.items() if not t.terminal and not t.claimed and t.blocked]
        text = " Workstream: {} on {} for .scratch/{}/ at {}. Owns: {}; shared paths are requests to the integrator.".format(
            stream.name, stream.branch, plan.slug, phase_label(plan), ", ".join(stream.owns) or "no paths declared")
        text += " Your tickets: {} claimed here{}; ready: {}; blocked: {}.".format(
            len(mine_claimed), " (" + claimed_label(plan, mine_claimed) + ")" if mine_claimed else "",
            ", ".join(num(n) for n in mine_ready) or "none", ", ".join(num(n) for n in mine_blocked) or "none")
        if mine_later:
            text += " Later phases: {} (after the gate).".format(", ".join(num(n) for n in mine_later))
        others = []
        for name, other in sorted(plan.workstreams.items()):
            if name == stream.name:
                continue
            awaiting = sum(1 for t in plan.tickets.values() if t.workstream == name and t.awaiting_integration)
            others.append("{} {} claimed".format(name, sum(1 for t in plan.tickets.values() if t.workstream == name and t.claimed))
                          + (", {} awaiting integration".format(awaiting) if awaiting else ""))
        if others:
            text += " Others: " + "; ".join(others) + "."
        text += " Plan: {} of {} done. Merge the integration branch {} before each claim.".format(c["done"], c["total"], plan.integration_branch)
        if plan.behind.get(stream.name):
            text += " This branch is behind {0}: git fetch and git merge the integration branch before your next claim.".format(plan.integration_branch)
        if stream.where != "here":
            place = "elsewhere" if stream.where == "elsewhere" else "on " + stream.where
            text += " Declared to run {}; do not claim here unless the user moved it.".format(place)
        parts.append(text)
    elif role == "integration" and plan is not None and not subagent:
        c = counts(plan)
        per = "; ".join("{} {} open".format(name, sum(1 for t in plan.tickets.values() if t.workstream == name and not t.terminal))
                        for name in sorted(plan.workstreams))
        awaiting = sum(1 for t in plan.tickets.values() if t.awaiting_integration)
        parts.append(" Integration checkout for .scratch/{}/ at {}: {} of {} done; {}{}. Claim only integrator tickets here; use the workstreams skill to integrate.".format(
            plan.slug, phase_label(plan), c["done"], c["total"], per, "; {} awaiting integration".format(awaiting) if awaiting else ""))
    elif role == "unmatched" and plan is not None and not subagent:
        parts.append(" Branch {} matches no workstream of .scratch/{}/; do not claim tickets here.".format(branch, plan.slug))
    else:
        for plan in active[:3]:
            c = counts(plan)
            claimed_text = " ({})".format(claimed_label(plan, c["claimed"])) if c["claimed"] else ""
            if subagent:
                parts.append(" Plan of record: .scratch/{}/ at {}: {} of {} done, {} claimed{}. Do not edit ticket files; the coordinating session owns Status.".format(
                    plan.slug, phase_label(plan), c["done"], c["total"], len(c["claimed"]), claimed_text))
            else:
                parts.append(" Plan of record: .scratch/{}/ at {}: {} of {} done, {} claimed{}, {} ready, {} blocked.".format(
                    plan.slug, phase_label(plan), c["done"], c["total"], len(c["claimed"]), claimed_text, c["ready"], c["blocked"]))
        if len(active) > 3:
            parts.append(" {} more active plans are on the board.".format(len(active) - 3))
        if not subagent:
            parts.append(" If the user's request is one of these tickets, claim it before changing code and state the phase and ticket in your first reply; an unrelated fix needs no ticket.")
    text = "".join(parts)
    if len(text) > BRIEF_LIMIT:
        text = text[:BRIEF_LIMIT - 3].rsplit(" ", 1)[0] + "..."
    return text


