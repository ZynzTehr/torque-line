def model(plans: List[Plan], notices: List[str]) -> Dict[str, object]:
    out: List[Dict[str, object]] = []
    for plan in plans:
        out.append({
            "slug": plan.slug, "kind": plan.kind, "active": plan.active, "completed": plan.completed,
            "current_phase": plan.current_phase, "frontier": plan.frontier, "attention": plan.attention,
            "errors": [{"ticket": n, "code": code} for n, code in sorted(plan.errors)], "notices": plan.notices,
            "phases": [dataclasses.asdict(phase) for _, phase in sorted(plan.phases.items())],
            "workstreams": [dataclasses.asdict(stream) for _, stream in sorted(plan.workstreams.items())],
            "base": plan.base, "integration": plan.integration_branch, "remote": plan.remote, "shared": plan.shared,
            "overlay": plan.overlay, "checkout_role": plan.checkout_role, "fetch_time": plan.fetch_time,
            "behind": plan.behind, "worktrees": plan.worktrees,
            "integration_order": [{"ticket": n, "branch": b, "sha": sha} for n, b, sha in plan.integration_order],
            "tickets": [{
                "number": t.number, "path": t.path, "title": t.title, "status": t.status, "blockers": t.blockers,
                "blocked": t.blocked, "phase": t.phase, "workstream": t.workstream, "claimed_by": t.claimed_by,
                "claimed_on": t.claimed_on.isoformat() if t.claimed_on else None, "verify": t.verify, "gate": t.gate,
                "acceptance": [t.acceptance_done, t.acceptance_total], "requests": t.requests, "errors": t.errors,
                "branch": t.branch, "integrated": t.integrated, "awaiting_integration": t.awaiting_integration,
                "done_sha": t.done_sha, "foreign_only": t.foreign_only,
            } for _, t in sorted(plan.tickets.items())],
        })
    return {"plans": out, "notices": notices}


def find_project(start: Path) -> Path:
    current = start.resolve()
    for candidate in (current, *current.parents):
        if (candidate / SCRATCH).is_dir() or (candidate / ".git").exists():
            return candidate
    return current


def parse_now(value: str) -> datetime.datetime:
    try:
        parsed = datetime.datetime.strptime(value, "%Y-%m-%dT%H:%M:%S%z")
    except ValueError:
        raise ProgressError("--now must look like 2026-10-20T12:00:00+00:00") from None
    return parsed.astimezone(datetime.timezone.utc)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project-root", type=Path)
    parser.add_argument("--write", action="store_true", help="write the gitignored PROGRESS.md instead of printing it")
    parser.add_argument("--json", action="store_true", help="print the derived model as JSON")
    parser.add_argument("--now", help="fixed UTC time, YYYY-MM-DDTHH:MM:SS+00:00")
    args = parser.parse_args(argv)
    try:
        project = checked_project(args.project_root) if args.project_root else find_project(Path.cwd())
        now = parse_now(args.now) if args.now else utcnow()
    except ProgressError as error:
        print(str(error), file=sys.stderr)
        return 2
    plans, notices = load(project, now)
    if args.json:
        print(json.dumps(model(plans, notices), indent=2, sort_keys=True))
    elif args.write:
        status = write_board(project, plans, now, notices)
        print("PROGRESS.md: " + status)
        if not plans:
            print("No plan of record under .scratch/.")
    else:
        if plans:
            print(render(plans, now, notices)[0], end="")
        else:
            print("No plan of record under .scratch/.")
    return 1 if any(plan.errors for plan in plans) else 0


if __name__ == "__main__":
    sys.exit(main())
